"""Render the Homebrew formula for one ControlLoop release.

Invoked by `.github/workflows/release.yml`'s `publish-homebrew` job after
the GitHub Release exists, never by product code. It takes the release
version and the combined `SHA256SUMS` file `attest-artifacts` wrote, and
prints a formula that installs the already-published, already-checksummed,
already-attested standalone binary for the machine it runs on:

- macOS on Apple Silicon: `controlloop-macos-arm64`
- Linux on x86_64: `controlloop-linux-x86_64`
- Linux on arm64: `controlloop-linux-arm64`

macOS on Intel has no binary (the same disclosed gap
`docs/reference/standalone-binaries.md` records), so the formula refuses
there with a message naming the alternative instead of failing inside
Homebrew with no explanation.

The formula is generated, never hand-edited, so a release can never ship a
formula whose checksums were typed by a person. Usage:

    python3 release-scripts/homebrew_formula.py \
        --version 0.2.0 \
        --checksums-file SHA256SUMS \
        --repository controlloop-security/controlloop \
        --output Formula/controlloop.rb

Dependency-free (standard library only), like the other release scripts.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

#: Asset name per Homebrew platform block, in the order the formula lists
#: them. Every name is one `build-binaries` matrix leg produces.
ASSETS: dict[str, str] = {
    "macos_arm": "controlloop-macos-arm64",
    "linux_intel": "controlloop-linux-x86_64",
    "linux_arm": "controlloop-linux-arm64",
}

_VERSION_RE = re.compile(r"^\d+\.\d+\.\d+$")
_SHA256_RE = re.compile(r"^[0-9a-f]{64}$")
_REPOSITORY_RE = re.compile(r"^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$")

_TEMPLATE = """\
# Generated by release-scripts/homebrew_formula.py in
# https://github.com/{repository} for ControlLoop v{version}.
# Do not edit by hand: the next release overwrites this file.
# No `version` line: Homebrew reads it from the release URL, and
# `brew audit --strict` rejects a redundant one.
class Controlloop < Formula
  desc "Local-first security scanner and deterministic CI gate for AI agents"
  homepage "https://controlloop.ai"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "{base}/{macos_arm}"
      sha256 "{macos_arm_sha}"
    end
  end

  on_linux do
    on_intel do
      url "{base}/{linux_intel}"
      sha256 "{linux_intel_sha}"
    end
    on_arm do
      url "{base}/{linux_arm}"
      sha256 "{linux_arm_sha}"
    end
  end

  def install
    if OS.mac? && Hardware::CPU.intel?
      odie "ControlLoop publishes no macOS Intel (x86_64) binary yet. " \\
           "Install it with `uv tool install controlloop` " \\
           "or `pipx install controlloop` instead."
    end
    binary = Dir["controlloop-*"].first
    odie "no ControlLoop binary was downloaded for this platform" if binary.nil?
    bin.install binary => "controlloop"
    chmod 0755, bin/"controlloop"
  end

  test do
    banner = shell_output("#{{bin}}/controlloop --version")
    assert_match "ControlLoop #{{version}}", banner
    (testpath/"agent-card.json").write <<~JSON
      {{"name": "report-agent",
       "skills": [{{"id": "read-metrics", "name": "read-metrics"}}]}}
    JSON
    report = shell_output("#{{bin}}/controlloop scan #{{testpath}} --format json")
    assert_match(/"verdict":\\s*"passed"/, report)
  end
end
"""


class FormulaError(ValueError):
    """Raised when the inputs cannot produce a trustworthy formula."""


def read_checksums(text: str) -> dict[str, str]:
    """Parse `sha256sum`-style lines (`<hex>  <name>`) into a mapping.

    Raises `FormulaError` on a malformed line rather than skipping it: a
    checksums file this script cannot read in full is not one to install
    from.
    """
    checksums: dict[str, str] = {}
    for line_number, raw in enumerate(text.splitlines(), start=1):
        line = raw.strip()
        if not line:
            continue
        parts = line.split(None, 1)
        if len(parts) != 2 or not _SHA256_RE.match(parts[0]):
            raise FormulaError(
                f"SHA256SUMS line {line_number} is not `<sha256>  <name>`: {raw!r}"
            )
        digest, name = parts
        name = name.lstrip("*")
        if name in checksums:
            raise FormulaError(f"SHA256SUMS names {name!r} twice")
        checksums[name] = digest
    return checksums


def render_formula(version: str, checksums: dict[str, str], repository: str) -> str:
    """Return the formula text, or raise `FormulaError` if an input is
    missing or malformed."""
    if not _VERSION_RE.match(version):
        raise FormulaError(f"version must be MAJOR.MINOR.PATCH, got {version!r}")
    if not _REPOSITORY_RE.match(repository):
        raise FormulaError(f"repository must be owner/name, got {repository!r}")
    missing = [asset for asset in ASSETS.values() if asset not in checksums]
    if missing:
        raise FormulaError(
            "SHA256SUMS has no entry for "
            + ", ".join(sorted(missing))
            + "; refusing to render a formula that could not verify its download"
        )
    base = f"https://github.com/{repository}/releases/download/v{version}"
    fields = {"version": version, "repository": repository, "base": base}
    for key, asset in ASSETS.items():
        fields[key] = asset
        fields[f"{key}_sha"] = checksums[asset]
    return _TEMPLATE.format(**fields)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--version", required=True, help="release version, MAJOR.MINOR.PATCH"
    )
    parser.add_argument(
        "--checksums-file",
        required=True,
        type=Path,
        help="the combined SHA256SUMS file the release pipeline wrote",
    )
    parser.add_argument(
        "--repository",
        default="controlloop-security/controlloop",
        help="GitHub owner/name whose release assets the formula downloads",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=None,
        help="where to write the formula (default: standard output)",
    )
    args = parser.parse_args(argv)
    try:
        checksums = read_checksums(args.checksums_file.read_text(encoding="utf-8"))
        formula = render_formula(args.version, checksums, args.repository)
    except (FormulaError, OSError) as error:
        print(f"homebrew_formula: {error}", file=sys.stderr)
        return 1
    if args.output is None:
        sys.stdout.write(formula)
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(formula, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
