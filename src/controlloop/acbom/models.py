KnownBoolean = bool | Literal["unknown"]

MAX_NODE_ATTRIBUTES = 32
"""At most this many keys in one `Node.attributes` map."""

MAX_ATTRIBUTE_VALUE_LENGTH = 512
"""The declared bound on one attribute value, in characters."""

ATTRIBUTE_TRUNCATION_MARKER = "...[truncated]"
"""Appended by `bound_attribute_text` when it shortens a value."""

AttributeKey = Annotated[
    str,
    StringConstraints(
        strict=True, min_length=1, max_length=64, pattern=r"^[a-z][a-z0-9_]*$"
    ),
]
AttributeValue = Annotated[
    str,
    StringConstraints(
        strict=True,
        min_length=1,
        max_length=MAX_ATTRIBUTE_VALUE_LENGTH,
        pattern=r"^[^\x00-\x1f\x7f]*$",
    ),
]

#: Attribute key fragments naming a category the map must never carry.
#: An attribute records what a file grants (an event name, a rule
#: pattern, a source type), never a value the grant protects.
_PROHIBITED_ATTRIBUTE_KEY_FRAGMENTS: tuple[str, ...] = (
    "value",
    "password",
    "passwd",
    "private_key",
    "prompt",
    "body",
    "output",
    "source_code",
    "source_content",
)


def bound_attribute_text(text: str) -> str:
    """Return `text` fit for a `Node.attributes` value.

    Control characters become spaces and surrounding whitespace is
    stripped. A value longer than `MAX_ATTRIBUTE_VALUE_LENGTH` is cut so
    that it ends in `ATTRIBUTE_TRUNCATION_MARKER` and fits the bound;
    the dropped tail is never returned or echoed. An empty result
    becomes `"unknown"`, since the map holds no empty values.

    This bounds a value; it does not redact one. Callers pass text
    through `controlloop.redaction.redact_text` first.
    """

    cleaned = re.sub(r"[\x00-\x1f\x7f]", " ", text).strip()
    if not cleaned:
        return "unknown"
    if len(cleaned) <= MAX_ATTRIBUTE_VALUE_LENGTH:
        return cleaned
    keep = MAX_ATTRIBUTE_VALUE_LENGTH - len(ATTRIBUTE_TRUNCATION_MARKER)
    return cleaned[:keep].rstrip() + ATTRIBUTE_TRUNCATION_MARKER


class _CanonicalModel(BaseModel):
    model_config = ConfigDict(
        extra="forbid",
        frozen=True,
        hide_input_in_errors=True,
        strict=True,
    )


class Generator(_CanonicalModel):
    """Generator identity recorded in an ACBOM envelope."""

    name: SafeIdentifier
    version: SemanticVersion


class Repository(_CanonicalModel):
    """Sanitized repository identity used by the canonical document."""

    commit: CommitIdentifier
    root_digest: Sha256Digest


class StandardIdentifier(_CanonicalModel):
    """Standards-native identifier attached to a node."""

    namespace: SafeIdentifier
    identifier: SafeIdentifier


class SecurityAttributes(_CanonicalModel):
    """Bounded, value-free security classifications for a node or edge."""

    trusted: KnownBoolean | None = None
    destructive: KnownBoolean | None = None
    read_only: KnownBoolean | None = None
    requires_approval: KnownBoolean | None = None
    approval_present: KnownBoolean | None = None
    privileged: KnownBoolean | None = None
    financial_action: KnownBoolean | None = None
    external_communication: KnownBoolean | None = None
    code_execution: KnownBoolean | None = None
    bypass_mode: KnownBoolean | None = None
    wildcard: KnownBoolean | None = None
    pinned: KnownBoolean | None = None
    untrusted_input: KnownBoolean | None = None
    sensitivity: Sensitivity | None = None
    data_classifications: Annotated[
        tuple[SafeIdentifier, ...],
        Field(max_length=64),
    ] = ()
    permission_scopes: Annotated[
        tuple[SafeIdentifier, ...],
        Field(max_length=128),
    ] = ()

    @model_validator(mode="after")
    def validate_unique_collections(self) -> Self:
        if len(set(self.data_classifications)) != len(self.data_classifications):
            raise ValueError("data classifications must be unique")
        if len(set(self.permission_scopes)) != len(self.permission_scopes):
            raise ValueError("permission scopes must be unique")
        return self


class Evidence(_CanonicalModel):
    """Sanitized provenance for a discovery or diagnostic."""

    adapter: SafeIdentifier
    path: RelativePath | None = None
    line_start: LineNumber | None = None
    line_end: LineNumber | None = None
    parser: SafeIdentifier | None = None
    schema_id: SafeIdentifier | None = None
    document_digest: Sha256Digest | None = None

    @model_validator(mode="after")
    def validate_location_and_line_range(self) -> Self:
        if self.path is None and self.document_digest is None:
            raise ValueError("evidence requires a path or document digest")
        if self.line_start is not None and self.path is None:
            raise ValueError("evidence line start requires a path")
        if self.line_end is not None:
            if self.path is None or self.line_start is None:
                raise ValueError("evidence line end requires a path and line start")
            if self.line_end < self.line_start:
                raise ValueError("evidence line end must not precede line start")
        return self


EvidenceCollection = Annotated[
    tuple[Evidence, ...],
    Field(min_length=1, max_length=32),
]


class AuthoritySubtype(StrEnum):
    """Subtypes for the agent authority contract.

    Each is bound to exactly one existing `NodeType` and carries the
    attribute keys and security flags its shape requires; see
    `AUTHORITY_SUBTYPE_RULES`.
    """

    HOST = "host"
    SUBAGENT = "subagent"
    HOOK = "hook"
    HELPER_COMMAND = "helper-command"
    PLUGIN = "plugin"
    MARKETPLACE = "marketplace"
    SKILL = "skill"
    WORKFLOW_RUNTIME = "workflow-runtime"
    PERMISSION_RULE = "permission-rule"


class AuthoritySubtypeRule(BaseModel):
    """The node type, attribute keys, and flags one subtype requires."""

    model_config = ConfigDict(frozen=True)

    node_type: NodeType
    required_attributes: tuple[str, ...] = ()
    required_flags: tuple[str, ...] = ()


AUTHORITY_SUBTYPE_RULES: dict[AuthoritySubtype, AuthoritySubtypeRule] = {
    AuthoritySubtype.HOST: AuthoritySubtypeRule(
        node_type=NodeType.AGENT, required_attributes=("host",)
    ),
    AuthoritySubtype.SUBAGENT: AuthoritySubtypeRule(node_type=NodeType.AGENT),
    AuthoritySubtype.HOOK: AuthoritySubtypeRule(
        node_type=NodeType.TOOL,
        required_attributes=("event", "hook_type"),
        required_flags=("code_execution",),
    ),
    AuthoritySubtype.HELPER_COMMAND: AuthoritySubtypeRule(
        node_type=NodeType.TOOL,
        required_attributes=("setting",),
        required_flags=("code_execution",),
    ),
    AuthoritySubtype.PLUGIN: AuthoritySubtypeRule(
        node_type=NodeType.TOOL,
        required_attributes=("source_type",),
        required_flags=("pinned",),
    ),
    AuthoritySubtype.MARKETPLACE: AuthoritySubtypeRule(
        node_type=NodeType.TOOL,
        required_attributes=("source_type",),
        required_flags=("pinned",),
    ),
    AuthoritySubtype.SKILL: AuthoritySubtypeRule(node_type=NodeType.TOOL),
    AuthoritySubtype.WORKFLOW_RUNTIME: AuthoritySubtypeRule(
        node_type=NodeType.TRIGGER, required_attributes=("job_permissions",)
    ),
    AuthoritySubtype.PERMISSION_RULE: AuthoritySubtypeRule(
        node_type=NodeType.PERMISSION,
        required_attributes=("effect", "pattern"),
        required_flags=("wildcard",),
    ),
}
"""Shape rules per authority subtype, mirrored by the packaged schema."""


def _validate_attributes(attributes: dict[str, str]) -> dict[str, str]:
    if len(attributes) > MAX_NODE_ATTRIBUTES:
        raise ValueError("node attributes exceed the declared key bound")
    for key in attributes:
        if any(fragment in key for fragment in _PROHIBITED_ATTRIBUTE_KEY_FRAGMENTS):
            raise ValueError("node attribute key names a prohibited value category")
    return attributes


NodeAttributes = Annotated[
    dict[AttributeKey, AttributeValue],
    AfterValidator(_validate_attributes),
]


class Node(_CanonicalModel):
    """Canonical graph node."""

    id: NodeId
    type: NodeType
    subtype: Subtype | None = None
    name: DisplayName
    security_attributes: SecurityAttributes
    confidence: Confidence
    evidence: EvidenceCollection
    standards_identifiers: Annotated[
        tuple[StandardIdentifier, ...],
        Field(max_length=32),
    ] = ()
    attributes: NodeAttributes = Field(default_factory=dict)

    def __hash__(self) -> int:
        # A frozen model hashes its field values, and a dict has no hash;
        # hash the attribute pairs in key order so equal nodes hash equal.
        return hash(
            (
                self.id,
                self.type,
                self.subtype,
                self.name,
                self.security_attributes,
                self.confidence,
                self.evidence,
                self.standards_identifiers,
                tuple(sorted(self.attributes.items())),
            )
        )

    @model_validator(mode="after")
    def validate_unique_collections(self) -> Self:
        if len(set(self.evidence)) != len(self.evidence):
            raise ValueError("node evidence must be unique")
        if len(set(self.standards_identifiers)) != len(self.standards_identifiers):
            raise ValueError("node standards identifiers must be unique")
        return self

    @model_validator(mode="after")
    def validate_authority_subtype_shape(self) -> Self:
        try:
            subtype = AuthoritySubtype(self.subtype) if self.subtype else None
        except ValueError:
            return self
        if subtype is None:
            return self
        rule = AUTHORITY_SUBTYPE_RULES[subtype]
        if self.type is not rule.node_type:
            raise ValueError("authority subtype is bound to a different node type")
        if any(key not in self.attributes for key in rule.required_attributes):
            raise ValueError("authority subtype is missing a required attribute")
        if any(
            getattr(self.security_attributes, flag) is None
            for flag in rule.required_flags
        ):
            raise ValueError("authority subtype is missing a required security flag")
        return self


