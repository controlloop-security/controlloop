"""Immutable canonical models for ACBOM schema, currently version 1.2.0.

Version 1.2.0 added the agent authority contract: four tri-state
`SecurityAttributes` flags (`bypass_mode`, `wildcard`, `pinned`,
`untrusted_input`), a bounded, value-free `Node.attributes` map, and
`AuthoritySubtype`, nine subtypes on existing node types for agent
hosts, hooks, helper commands, plugins, marketplaces, skills, subagents,
workflow runtimes, and permission rules. No node or edge type was added.

Version 1.1.0 added `ACBOMDocument.schema_url`, an optional,
backward-compatible field carrying the permanent, versioned URL this
exact document's schema is published at, so that every generated ACBOM
references its schema URL. A document generated by this codebase always
populates it; an externally supplied 1.0.0 document (predating the
field) parses fine without it, matching the MINOR-bump compatibility
policy documented in
`docs/reference/schema-versioning.md`. The frozen 1.0.0 schema file
(`src/controlloop/schemas/acbom/1.0.0/`) is never edited to add it."""

from __future__ import annotations

import re
from enum import StrEnum
from typing import Annotated, Literal, Self

from pydantic import (
    AfterValidator,
    BaseModel,
    ConfigDict,
    Field,
    StringConstraints,
    model_validator,
)

_SEMANTIC_VERSION_PATTERN = (
    r"^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)"
    r"(?:-[0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*)?"
    r"(?:\+[0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*)?$"
)
_RELATIVE_PATH_PATTERN = re.compile(
    r"^(?!/)(?!.*\\)(?!.*(?:^|/)\.\.?(?:/|$))[^\x00-\x1f\x7f]+$"
)

SafeIdentifier = Annotated[
    str,
    StringConstraints(
        strict=True,
        min_length=1,
        max_length=256,
        pattern=r"^[A-Za-z0-9][A-Za-z0-9._:/@+-]*$",
    ),
]
SafeText = Annotated[
    str,
    StringConstraints(
        strict=True,
        min_length=1,
        max_length=1024,
        pattern=r"^[^\x00-\x1f\x7f]*$",
    ),
]
SemanticVersion = Annotated[
    str,
    StringConstraints(
        strict=True,
        min_length=5,
        max_length=64,
        pattern=_SEMANTIC_VERSION_PATTERN,
    ),
]
Sha256Digest = Annotated[
    str,
    StringConstraints(strict=True, pattern=r"^sha256:[0-9a-f]{64}$"),
]
#: A schema URL's validated shape only --
#: `https://` anchored, no control characters, length-bounded. Mirrors
#: `controlloop.findings.models.DocumentationUrl`'s identical shape
#: exactly, applied here to a different field. Never fetched.
SchemaUrl = Annotated[
    str,
    StringConstraints(
        strict=True,
        min_length=len("https://x"),
        max_length=2048,
        pattern=r"^https://[^\x00-\x1f\x7f\s]+$",
    ),
]
NodeId = Annotated[
    str,
    StringConstraints(
        strict=True,
        pattern=(
            r"^clp:(?:agent|tool|resource|identity|permission|data-class|trigger|"
            r"policy-boundary):sha256:[0-9a-f]{64}$"
        ),
    ),
]
EdgeId = Annotated[
    str,
    StringConstraints(
        strict=True,
        pattern=r"^clp:edge:sha256:[0-9a-f]{64}$",
    ),
]
Subtype = Annotated[
    str,
    StringConstraints(
        strict=True,
        min_length=1,
        max_length=128,
        pattern=r"^[a-z][a-z0-9._-]*$",
    ),
]
DisplayName = Annotated[
    str,
    StringConstraints(
        strict=True,
        min_length=1,
        max_length=256,
        pattern=r"^[^\x00-\x1f\x7f]*$",
    ),
]
CommitIdentifier = Annotated[
    str,
    StringConstraints(
        strict=True,
        min_length=1,
        max_length=128,
        pattern=r"^[A-Za-z0-9][A-Za-z0-9._:/@+-]*$",
    ),
]
DiagnosticCode = Annotated[
    str,
    StringConstraints(
        strict=True,
        min_length=1,
        max_length=64,
        pattern=r"^[A-Z][A-Z0-9]*(?:-[A-Z0-9]+)*$",
    ),
]
LineNumber = Annotated[int, Field(strict=True, ge=1, le=10_000_000)]


def _validate_relative_path(value: str) -> str:
    if _RELATIVE_PATH_PATTERN.fullmatch(value) is None:
        raise ValueError("path must be a sanitized repository-relative path")
    return value


RelativePath = Annotated[
    str,
    StringConstraints(strict=True, min_length=1, max_length=512),
    AfterValidator(_validate_relative_path),
]


