class ACBOMDocument(_CanonicalModel):
    """Complete immutable ACBOM document."""

    schema_version: SemanticVersion
    generator: Generator
    repository: Repository
    nodes: Annotated[tuple[Node, ...], Field(max_length=10_000)]
    edges: Annotated[tuple[Edge, ...], Field(max_length=50_000)]
    diagnostics: Annotated[tuple[Diagnostic, ...], Field(max_length=1_000)]
    digest: Sha256Digest
    schema_url: SchemaUrl | None = None

    @model_validator(mode="after")
    def validate_graph_integrity(self) -> Self:
        node_ids = [node.id for node in self.nodes]
        if len(set(node_ids)) != len(node_ids):
            raise ValueError("node IDs must be unique")

        edge_ids = [edge.id for edge in self.edges]
        if len(set(edge_ids)) != len(edge_ids):
            raise ValueError("edge IDs must be unique")

        known_node_ids = set(node_ids)
        if any(
            edge.source not in known_node_ids or edge.target not in known_node_ids
            for edge in self.edges
        ):
            raise ValueError("edge endpoints must reference document node IDs")
        return self
