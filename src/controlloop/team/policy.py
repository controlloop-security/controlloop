"""Strengthen-only policy merge, CLI side.

A repository may tighten what its organization requires. It may never
loosen it. `docs/reference/policy-merge-semantics.md` states those rules
for users and the platform implements them on its side; this module
implements the identical function for the CLI, so a gate can tell a
developer *before* the upload what the server would compute *after* it.

## Why the same logic exists twice, and how the two are kept honest

The CLI must decide a verdict locally -- that is the entire product -- and
the server must record an effective policy it computed itself rather than
one a client asserted. Neither side can delegate to the other. So the
function exists twice, and the risk is that the copies drift and a gate
passes locally while the platform records a different effective policy for
the same scan.

The platform contract's `policy-merge-vectors.json` (copied into
`tests/fixtures/contract/`) is the control. It is a
language-neutral vector set -- inputs and the exact expected merge output
-- placed next to the contract rather than inside either implementation,
because it belongs to neither. `tests/team/test_policy_merge.py`
asserts this module against every vector.

**Disclosed limitation:** in this repository the vectors bind the CLI
only. They were generated by running the *platform's* implementation and
recording its real output, and this module was written to match that
recorded output, so the two agree by construction. Keeping them agreeing
depends on refreshing the vectors whenever the platform's contract
changes (see `tests/fixtures/contract/README.md`).

## Determinism

Pure: no clock, no environment, no I/O, no randomness. Inputs are indexed
by identity and outputs are emitted sorted, so two callers that list their
rules in different orders get identical results.

## What the CLI does with the merged policy, and what it does not

`enabled: false` on a merged rule disables that rule for local evaluation.
A merged `severity_floor` raises a finding's severity to the floor when it
sits below it (`apply_severity_floors`). A merged `action` decides what a
finding from that rule does to the verdict
(`controlloop.policy.thresholds.evaluate_gate`); a rule without one keeps
the severity-against-threshold behaviour.

`approved_components` is merged strengthen-only too (merge semantics
1.1.0): a repository may drop an organization entry or narrow its
constraints (`package`, `version_range`, `digest`, `command_pattern`,
`pin_required`), never add one or widen it. The effective list is what
`policy.unsanctioned-agent-component` judges the authority delta against
(`controlloop.team.sanction`), and the platform contract's
`policy_merge_vectors.json` holds this function to the platform's merge
for constrained entries.
"""

from __future__ import annotations

from dataclasses import dataclass, replace
from typing import Final

from controlloop.findings.models import Finding, FindingSeverity
from controlloop.team.sanction import ApprovedEntry, narrowed_entry, widened_fields

#: Severity ordering, weakest first. Mirrors the platform's
#: `SEVERITY_ORDER` exactly; the two
#: are compared by `tests/team/test_policy_merge.py` through the shared
#: vectors rather than by importing across the boundary.
SEVERITY_ORDER: Final = ("info", "low", "medium", "high", "critical")

#: The merge semantics this module implements. Recorded in evidence
#: alongside the organization bundle version so a verdict stays
#: re-derivable when these rules are later revised.
#: 1.1.0: approved-component
#: constraints merge strengthen-only. An entry without constraints merges
#: exactly as under 1.0.0.
#: 1.2.0: a rule's `action` merges strengthen-only in `ACTION_ORDER`. A
#: rule without an `action` merges exactly as under 1.1.0.
MERGE_SEMANTICS_VERSION: Final = "1.2.0"

#: Rule actions, weakest first. Mirrors the platform's `ACTION_ORDER`.
ACTION_ORDER: Final = ("pass", "warn", "require_review", "fail")

#: What an organization rule without an `action` compares as when a
#: repository proposes one: the platform's stored default.
DEFAULT_ACTION: Final = "fail"


def _rank(severity: str) -> int:
    """Comparable rank, or `-1` for a severity this codebase does not know.

    `-1` makes an unrecognized value weaker than every recognized one, so a
    repository proposing one is rejected rather than silently accepted:
    "unknown, therefore allowed" is the wrong default for a security
    control. Matches the platform's `_rank` exactly, including that
    treatment.
    """

    try:
        return SEVERITY_ORDER.index(severity)
    except ValueError:
        return -1


def _action_rank(action: str) -> int:
    """Comparable rank, or `-1` for an action this codebase does not know,
    for the same reason `_rank` gives an unknown severity `-1`."""

    try:
        return ACTION_ORDER.index(action)
    except ValueError:
        return -1


@dataclass(frozen=True, slots=True)
class RuleSpec:
    """One rule's configuration, on either side of the merge.

    `mandatory` is meaningful only on the organization side; a repository
    cannot declare its own rule mandatory, and the merge sets `False` for
    rules the organization never configured.

    `action` is what a finding from this rule does to a Team gate's
    verdict (`ACTION_ORDER`); `None` leaves the verdict to the finding's
    severity against `severity_threshold`.
    """

    rule_id: str
    enabled: bool = True
    severity_floor: str | None = None
    mandatory: bool = False
    action: str | None = None


#: One approved-component entry with its constraints. The name is
#: kept for the existing call sites; the type is
#: `controlloop.team.sanction.ApprovedEntry`.
ApprovedComponentSpec = ApprovedEntry


@dataclass(frozen=True, slots=True)
class MergeRejection:
    """One weakening attempt, explained.

    Names the rule and the organization bundle version that forbade it, so
    the message says what to change and what governs it.
    """

    rule_id: str
    organization_bundle_version: str
    reason: str


@dataclass(frozen=True, slots=True)
class MergeResult:
    """The effective policy, or the reasons it cannot be produced."""

    rules: tuple[RuleSpec, ...]
    approved_components: tuple[ApprovedComponentSpec, ...]
    rejections: tuple[MergeRejection, ...] = ()

    @property
    def accepted(self) -> bool:
        return not self.rejections

    def disabled_rule_ids(self) -> frozenset[str]:
        """Rule IDs the effective policy turns off, for the local
        evaluation pass."""

        return frozenset(rule.rule_id for rule in self.rules if not rule.enabled)

    def severity_floors(self) -> dict[str, str]:
        """Per-rule severity floors the effective policy sets."""

        return {
            rule.rule_id: rule.severity_floor
            for rule in self.rules
            if rule.severity_floor is not None
        }

    def actions(self) -> dict[str, str]:
        """Per-rule actions the effective policy sets."""

        return {
            rule.rule_id: rule.action for rule in self.rules if rule.action is not None
        }


def merge_policy(
    *,
    organization_rules: tuple[RuleSpec, ...],
    organization_components: tuple[ApprovedComponentSpec, ...],
    repository_rules: tuple[RuleSpec, ...] = (),
    repository_components: tuple[ApprovedComponentSpec, ...] = (),
    organization_bundle_version: str,
) -> MergeResult:
    """Merge repository policy into an organization bundle, strengthen-only.

    Every classification here is the one stated in
    `docs/reference/policy-merge-semantics.md`:

    | Repository asks to | Classified as | Result |
    | --- | --- | --- |
    | Raise a rule's severity floor | tightening | applied |
    | Raise a rule's action | tightening | applied |
    | Disable a non-mandatory rule | tightening | applied |
    | Add a rule the organization did not configure | tightening | applied |
    | Remove an approved-component entry | tightening | applied |
    | Narrow an approved component's constraints | tightening | applied |
    | Lower a rule's severity floor | weakening | rejected |
    | Lower a rule's action | weakening | rejected |
    | Disable a mandatory rule | weakening | rejected |
    | Add an approved-component entry | weakening | rejected |
    | Widen an approved component's constraints | weakening | rejected |
    """

    organization_by_id = {rule.rule_id: rule for rule in organization_rules}
    effective = dict(organization_by_id)
    rejections: list[MergeRejection] = []

    for override in repository_rules:
        organization_rule = organization_by_id.get(override.rule_id)

        if organization_rule is None:
            # A rule the organization never configured. Adding one can only
            # add findings, so it is a tightening. `mandatory` is forced
            # false: a repository does not get to bind itself in a way the
            # organization did not.
            effective[override.rule_id] = replace(override, mandatory=False)
            continue

        if not override.enabled:
            if organization_rule.mandatory:
                rejections.append(
                    MergeRejection(
                        rule_id=override.rule_id,
                        organization_bundle_version=organization_bundle_version,
                        reason=(
                            f"Repository policy disables `{override.rule_id}`, "
                            f"which organization policy version "
                            f"{organization_bundle_version} marks mandatory. "
                            f"Repository policy may tighten a mandatory rule "
                            f"but never disable it."
                        ),
                    )
                )
                # Deliberately skips this override's severity floor too,
                # matching the platform: an override that was refused is
                # refused whole, not partly applied.
                continue
            effective[override.rule_id] = replace(
                effective[override.rule_id], enabled=False
            )

        if override.severity_floor is not None:
            organization_floor = _rank(organization_rule.severity_floor or "")
            repository_floor = _rank(override.severity_floor)
            if repository_floor < organization_floor:
                rejections.append(
                    MergeRejection(
                        rule_id=override.rule_id,
                        organization_bundle_version=organization_bundle_version,
                        reason=(
                            f"Repository policy lowers the severity floor of "
                            f"`{override.rule_id}` from "
                            f"`{organization_rule.severity_floor}` to "
                            f"`{override.severity_floor}`, which organization "
                            f"policy version {organization_bundle_version} does "
                            f"not permit. A repository may raise a floor, never "
                            f"lower it."
                        ),
                    )
                )
                continue
            effective[override.rule_id] = replace(
                effective[override.rule_id],
                severity_floor=override.severity_floor,
            )

        if override.action is not None:
            organization_action = organization_rule.action or DEFAULT_ACTION
            if _action_rank(override.action) < _action_rank(organization_action):
                rejections.append(
                    MergeRejection(
                        rule_id=override.rule_id,
                        organization_bundle_version=organization_bundle_version,
                        reason=(
                            f"Repository policy lowers the action of "
                            f"`{override.rule_id}` from `{organization_action}` "
                            f"to `{override.action}`, which organization policy "
                            f"version {organization_bundle_version} does not "
                            f"permit. A repository may raise an action, never "
                            f"lower it."
                        ),
                    )
                )
                continue
            effective[override.rule_id] = replace(
                effective[override.rule_id], action=override.action
            )

    organization_by_key = {
        component.key: component for component in organization_components
    }
    repository_by_key: dict[tuple[str, str], ApprovedComponentSpec] = {}

    for component in repository_components:
        key = component.key
        organization_entry = organization_by_key.get(key)
        if organization_entry is None:
            rejections.append(
                MergeRejection(
                    rule_id=f"approved-component:{key[0]}:{key[1]}",
                    organization_bundle_version=organization_bundle_version,
                    reason=(
                        f"Repository policy approves the {key[0]} "
                        f"`{key[1]}`, which organization policy version "
                        f"{organization_bundle_version} does not list. A "
                        f"repository may remove an approved component, never "
                        f"add one."
                    ),
                )
            )
            continue
        widened = widened_fields(organization_entry, component.to_mapping())
        if widened:
            fields = ", ".join(f"`{name}`" for name in widened)
            rejections.append(
                MergeRejection(
                    rule_id=f"approved-component:{key[0]}:{key[1]}",
                    organization_bundle_version=organization_bundle_version,
                    reason=(
                        f"Repository policy widens {fields} of the {key[0]} "
                        f"`{key[1]}` beyond what organization policy version "
                        f"{organization_bundle_version} approves. A repository "
                        f"may narrow an approved component, never widen it."
                    ),
                )
            )
            continue
        repository_by_key[key] = component

    if repository_components:
        # Narrowing: the repository's list is the intersection, so an entry
        # it omits is dropped rather than kept, and an entry it restates
        # keeps every organization constraint it does not narrow.
        listed = {component.key for component in repository_components}
        effective_components = [
            narrowed_entry(entry, repository_by_key[key].to_mapping())
            if key in repository_by_key
            else entry
            for key, entry in organization_by_key.items()
            if key in listed
        ]
    else:
        effective_components = list(organization_by_key.values())

    return MergeResult(
        rules=tuple(sorted(effective.values(), key=lambda rule: rule.rule_id)),
        approved_components=tuple(
            sorted(effective_components, key=lambda component: component.key)
        ),
        rejections=tuple(sorted(rejections, key=lambda rejection: rejection.rule_id)),
    )


def apply_severity_floors(
    findings: tuple[Finding, ...], floors: dict[str, str]
) -> tuple[Finding, ...]:
    """Raise each finding's severity to its rule's floor, where one applies.

    Raising only, never lowering: a floor is "the lowest severity this rule
    may report under this bundle," so a finding already at or above it is
    untouched, and a floor can never quiet a finding that was louder.

    A floor naming a severity this CLI does not recognize is ignored rather
    than applied, for the same reason `_rank` treats it as weakest: an
    unrecognized value cannot be shown to tighten anything, and guessing at
    it would change a verdict on the strength of a typo.
    """

    if not floors:
        return findings

    raised: list[Finding] = []
    for finding in findings:
        floor = floors.get(finding.rule_id)
        if floor is None or _rank(floor) < 0:
            raised.append(finding)
            continue
        if _rank(finding.severity.value) >= _rank(floor):
            raised.append(finding)
            continue
        raised.append(finding.model_copy(update={"severity": FindingSeverity(floor)}))
    return tuple(raised)
