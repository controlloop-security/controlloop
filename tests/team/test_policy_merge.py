"""Tests for the strengthen-only merge.

The centerpiece is `TestSharedVectors`, which asserts
`controlloop.team.policy.merge_policy` against every vector in
`tests/fixtures/contract/policy-merge-vectors.json`. Those vectors were
generated by running the platform's own merge and recording its real
output, so this file is the CLI half of the shared golden vectors that
keep the CLI and platform from ever disagreeing on an effective policy.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest
from factories import make_finding

from controlloop.acbom.models import Confidence
from controlloop.findings.models import Finding, FindingSeverity
from controlloop.team.policy import (
    SEVERITY_ORDER,
    ApprovedComponentSpec,
    MergeResult,
    RuleSpec,
    apply_severity_floors,
    merge_policy,
)

_VECTORS_PATH = (
    Path(__file__).resolve().parents[1]
    / "fixtures"
    / "contract"
    / "policy-merge-vectors.json"
)


def _load_vectors() -> list[dict[str, Any]]:
    document = json.loads(_VECTORS_PATH.read_text(encoding="utf-8"))
    vectors = document["vectors"]
    assert isinstance(vectors, list)
    assert vectors, "the shared vector file must not be empty"
    return vectors


def _rules(raw: list[dict[str, Any]]) -> tuple[RuleSpec, ...]:
    return tuple(
        RuleSpec(
            rule_id=item["rule_id"],
            enabled=item.get("enabled", True),
            severity_floor=item.get("severity_floor"),
            mandatory=item.get("mandatory", False),
        )
        for item in raw
    )


def _components(raw: list[dict[str, Any]]) -> tuple[ApprovedComponentSpec, ...]:
    return tuple(
        ApprovedComponentSpec(type=item["type"], name_pattern=item["name_pattern"])
        for item in raw
    )


def _as_json(result: MergeResult) -> dict[str, Any]:
    """Render a `MergeResult` in the vector file's own shape, so the
    comparison is against the recorded backend output rather than against
    a Python-specific repr."""

    return {
        "rules": [
            {
                "rule_id": rule.rule_id,
                "enabled": rule.enabled,
                "severity_floor": rule.severity_floor,
                "mandatory": rule.mandatory,
            }
            for rule in result.rules
        ],
        "approved_components": [
            {"type": component.type, "name_pattern": component.name_pattern}
            for component in result.approved_components
        ],
        "rejections": [
            {
                "rule_id": rejection.rule_id,
                "organization_bundle_version": (rejection.organization_bundle_version),
                "reason": rejection.reason,
            }
            for rejection in result.rejections
        ],
    }


def _merge(vector: dict[str, Any]) -> MergeResult:
    return merge_policy(
        organization_rules=_rules(vector["organization"]["rules"]),
        organization_components=_components(
            vector["organization"]["approved_components"]
        ),
        repository_rules=_rules(vector["repository"]["rules"]),
        repository_components=_components(vector["repository"]["approved_components"]),
        organization_bundle_version=vector["organization_bundle_version"],
    )


_VECTORS = _load_vectors()


class TestSharedVectors:
    """The CLI merge reproduces the platform merge exactly."""

    @pytest.mark.parametrize(
        "vector", _VECTORS, ids=[vector["name"] for vector in _VECTORS]
    )
    def test_cli_merge_matches_the_recorded_platform_output(
        self, vector: dict[str, Any]
    ) -> None:
        assert _as_json(_merge(vector)) == vector["expected"]

    def test_the_vector_file_covers_every_documented_classification(self) -> None:
        """A vector file that drifted into covering only the easy cases
        would still pass every assertion above while proving nothing. This
        holds it to the seven classifications
        `docs/reference/policy-merge-semantics.md` tabulates, plus the
        unrecognized-severity rule that page states in prose."""

        names = {vector["name"] for vector in _VECTORS}
        assert {
            "repository-raises-a-severity-floor",
            "repository-lowers-a-severity-floor",
            "repository-disables-a-non-mandatory-rule",
            "repository-disables-a-mandatory-rule",
            "repository-adds-a-rule-the-organization-never-configured",
            "repository-removes-an-approved-component",
            "repository-adds-an-approved-component",
            "repository-proposes-an-unrecognized-severity",
        } <= names

    def test_every_weakening_vector_actually_rejects(self) -> None:
        """The negative controls are negative, and the positive ones are
        positive.

        Without this, a vector whose expected output had been recorded
        from a broken implementation would lock the bug in: every
        assertion above would still pass, because they compare against
        that same recorded output. This names, independently of the file,
        which vectors must reject and which must not.
        """

        weakening = {
            "repository-lowers-a-severity-floor",
            "repository-disables-a-mandatory-rule",
            "repository-adds-an-approved-component",
            "repository-proposes-an-unrecognized-severity",
            "a-refused-override-is-refused-whole",
            "several-weakenings-are-all-reported",
        }
        tightening = {
            "repository-raises-a-severity-floor",
            "repository-disables-a-non-mandatory-rule",
            "repository-adds-a-rule-the-organization-never-configured",
            "repository-removes-an-approved-component",
        }
        seen_weakening: set[str] = set()
        seen_tightening: set[str] = set()

        for vector in _VECTORS:
            result = _merge(vector)
            if vector["name"] in weakening:
                assert result.rejections, vector["name"]
                assert not result.accepted
                seen_weakening.add(vector["name"])
            elif vector["name"] in tightening:
                assert not result.rejections, vector["name"]
                assert result.accepted
                seen_tightening.add(vector["name"])

        assert seen_weakening == weakening
        assert seen_tightening == tightening

    def test_a_refused_override_is_not_partly_applied(self) -> None:
        """The subtle one, and the reason it has its own vector: an
        override that both disables a mandatory rule and raises its
        severity floor is refused *whole*. Applying the floor while
        refusing the disable would leave the repository enforcing a policy
        neither side ever asked for."""

        vector = next(
            item
            for item in _VECTORS
            if item["name"] == "a-refused-override-is-refused-whole"
        )
        result = _merge(vector)

        assert result.rejections
        assert result.rules[0].severity_floor == "low"
        assert result.rules[0].enabled is True


class TestDeterminism:
    """The merge is deterministic and order-independent."""

    def test_the_same_inputs_produce_the_same_result(self) -> None:
        for vector in _VECTORS:
            assert _as_json(_merge(vector)) == _as_json(_merge(vector))

    def test_reordering_the_inputs_does_not_change_the_output(self) -> None:
        vector = next(
            item
            for item in _VECTORS
            if item["name"] == "input-order-does-not-change-the-result"
        )
        forward = _merge(vector)

        reversed_vector = {
            **vector,
            "organization": {
                "rules": list(reversed(vector["organization"]["rules"])),
                "approved_components": list(
                    reversed(vector["organization"]["approved_components"])
                ),
            },
        }
        assert _as_json(_merge(reversed_vector)) == _as_json(forward)

    def test_the_merge_reads_no_clock_or_environment(self) -> None:
        """A structural check, not a behavioral one: the module that
        decides a verdict input must not import a source of ambient
        state."""

        source = (
            Path(__file__).resolve().parents[2]
            / "src"
            / "controlloop"
            / "team"
            / "policy.py"
        ).read_text(encoding="utf-8")
        for forbidden in ("import os", "import random", "import time", "datetime"):
            assert f"\n{forbidden}" not in source, forbidden


class TestRejectionMessages:
    """A rejection names the rule and the organization policy version."""

    def test_a_disabled_mandatory_rule_names_both(self) -> None:
        result = merge_policy(
            organization_rules=(RuleSpec("capability.new-tool", mandatory=True),),
            organization_components=(),
            repository_rules=(RuleSpec("capability.new-tool", enabled=False),),
            organization_bundle_version="7",
        )

        assert len(result.rejections) == 1
        rejection = result.rejections[0]
        assert rejection.rule_id == "capability.new-tool"
        assert rejection.organization_bundle_version == "7"
        assert "capability.new-tool" in rejection.reason
        assert "version 7" in rejection.reason
        assert "mandatory" in rejection.reason

    def test_a_lowered_floor_names_both_severities(self) -> None:
        result = merge_policy(
            organization_rules=(RuleSpec("secrets.hardcoded", severity_floor="high"),),
            organization_components=(),
            repository_rules=(RuleSpec("secrets.hardcoded", severity_floor="low"),),
            organization_bundle_version="12",
        )

        assert "`high`" in result.rejections[0].reason
        assert "`low`" in result.rejections[0].reason

    def test_every_weakening_is_reported_not_only_the_first(self) -> None:
        result = merge_policy(
            organization_rules=(
                RuleSpec("a.rule", mandatory=True),
                RuleSpec("b.rule", severity_floor="high"),
            ),
            organization_components=(),
            repository_rules=(
                RuleSpec("a.rule", enabled=False),
                RuleSpec("b.rule", severity_floor="info"),
            ),
            organization_bundle_version="3",
        )

        assert [rejection.rule_id for rejection in result.rejections] == [
            "a.rule",
            "b.rule",
        ]


class TestAccessors:
    def test_disabled_rule_ids_reports_the_effective_disables(self) -> None:
        result = merge_policy(
            organization_rules=(RuleSpec("a.rule"), RuleSpec("b.rule")),
            organization_components=(),
            repository_rules=(RuleSpec("a.rule", enabled=False),),
            organization_bundle_version="1",
        )

        assert result.disabled_rule_ids() == frozenset({"a.rule"})

    def test_severity_floors_reports_only_rules_that_set_one(self) -> None:
        result = merge_policy(
            organization_rules=(
                RuleSpec("a.rule", severity_floor="high"),
                RuleSpec("b.rule"),
            ),
            organization_components=(),
            organization_bundle_version="1",
        )

        assert result.severity_floors() == {"a.rule": "high"}


def _finding(rule_id: str, severity: FindingSeverity) -> Finding:
    return make_finding(rule_id=rule_id, severity=severity)


class TestSeverityFloors:
    """`apply_severity_floors` raises, never lowers."""

    def test_a_finding_below_the_floor_is_raised_to_it(self) -> None:
        findings = (_finding("a.rule", FindingSeverity.LOW),)

        raised = apply_severity_floors(findings, {"a.rule": "high"})

        assert raised[0].severity is FindingSeverity.HIGH

    def test_a_finding_above_the_floor_is_untouched(self) -> None:
        findings = (_finding("a.rule", FindingSeverity.CRITICAL),)

        raised = apply_severity_floors(findings, {"a.rule": "medium"})

        assert raised[0].severity is FindingSeverity.CRITICAL

    def test_a_finding_at_the_floor_is_untouched(self) -> None:
        findings = (_finding("a.rule", FindingSeverity.MEDIUM),)

        raised = apply_severity_floors(findings, {"a.rule": "medium"})

        assert raised[0] == findings[0]

    def test_a_rule_with_no_floor_is_untouched(self) -> None:
        findings = (_finding("a.rule", FindingSeverity.INFO),)

        raised = apply_severity_floors(findings, {"other.rule": "critical"})

        assert raised[0].severity is FindingSeverity.INFO

    def test_an_unrecognized_floor_is_ignored_not_guessed_at(self) -> None:
        findings = (_finding("a.rule", FindingSeverity.INFO),)

        raised = apply_severity_floors(findings, {"a.rule": "catastrophic"})

        assert raised[0].severity is FindingSeverity.INFO

    def test_no_floors_returns_the_identical_tuple(self) -> None:
        findings = (_finding("a.rule", FindingSeverity.INFO),)

        assert apply_severity_floors(findings, {}) is findings

    def test_every_severity_in_the_order_is_a_real_finding_severity(self) -> None:
        """Guards `SEVERITY_ORDER` against drifting from the enum it
        ranks -- the same drift guard `test_policy_thresholds.py` already
        applies to `controlloop.config`'s literal severity set."""

        assert set(SEVERITY_ORDER) == {member.value for member in FindingSeverity}

    def test_confidence_is_not_a_severity(self) -> None:
        """A guard against the easy copy-paste error of ranking the wrong
        enum: `Confidence` and `FindingSeverity` overlap on three member
        names."""

        assert set(SEVERITY_ORDER) != {member.value for member in Confidence}
