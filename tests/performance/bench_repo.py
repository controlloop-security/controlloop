"""A deterministic, representative ~100,000-line benchmark repository
generator.

Generated at benchmark time rather than committed, matching the
convention against committing large synthetic fixture directories (the
git-nesting trap). A fixed seed makes every generated byte identical run
to run: file count, per-file line count, and per-line content.

The generated repository plants two real, adapter-detectable
declaration files (`.mcp.json`, `openapi.json`) alongside the
generated bulk, so the benchmark measures a *representative*
repository -- real declarations buried in ordinary source content --
not merely a stress test of the traversal bounds (the
decompression-bomb and pathological-depth fixtures already cover
that, separately).
"""

from __future__ import annotations

import json
import random
from pathlib import Path

TARGET_LINE_COUNT = 100_000
"""The benchmark's "100,000-line" target."""

_SEED = 42
_MIN_LINES_PER_FILE = 50
_MAX_LINES_PER_FILE = 400


def build_benchmark_repository(root: Path) -> int:
    """Populate `root` with a deterministic, representative repository.

    Returns the exact total line count written (never below
    `TARGET_LINE_COUNT`, since files are written whole -- the final
    file may push the total slightly past the target rather than
    truncate mid-file).
    """

    rng = random.Random(_SEED)
    total_lines = 0
    file_index = 0

    while total_lines < TARGET_LINE_COUNT:
        file_index += 1
        line_count = rng.randint(_MIN_LINES_PER_FILE, _MAX_LINES_PER_FILE)
        path = root / "src" / f"module_{file_index}.py"
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("w") as handle:
            for line in range(line_count):
                handle.write(
                    f"def func_{file_index}_{line}(value):\n"
                    f"    return value + {rng.randint(0, 1_000_000)}\n"
                )
        total_lines += line_count * 2

    (root / ".mcp.json").write_text(
        json.dumps(
            {"mcpServers": {"files": {"command": "npx", "args": ["mcp-server-files"]}}}
        )
    )
    (root / "openapi.json").write_text(
        json.dumps(
            {
                "openapi": "3.0.0",
                "paths": {"/widgets": {"get": {"operationId": "listWidgets"}}},
            }
        )
    )

    return total_lines
